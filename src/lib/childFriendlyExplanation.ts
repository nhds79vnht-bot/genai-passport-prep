const dictionary = rows.map(([term, meaning, example, aliases]) => ({
  term,
  meaning,
  example,
  terms: [term, ...(aliases?.split('|') ?? [])].filter(Boolean),
}))

const matches = (text: string, aliases: readonly string[]): boolean =>
  aliases.some((alias) => text.toLocaleLowerCase('ja-JP').includes(alias.toLocaleLowerCase('ja-JP')))

/**
 * For each question, prefer its own topic, then its prompt, then its reason.
 * Never define terms that appear only in a wrong answer. Cap to 3 to keep
 * the learning screen short on iPhone. No generative API is invoked.
 */
export function getChildFriendlyTerms(question: Pick<Question, 'topic' | 'prompt' | 'explanation'>): EasyTerm[] {
  return dictionary
    .map((entry) => {
      const rank = matches(question.topic, entry.terms) ? 3 : matches(question.prompt, entry.terms) ? 2 : matches(question.explanation, entry.terms) ? 1 : 0
      const specificity = Math.max(...entry.terms.map((alias) => alias.length))
      return { ...entry, rank, specificity }
    })
    .filter((entry) => entry.rank > 0)
    .sort((a, b) => b.rank - a.rank || b.specificity - a.specificity)
    .slice(0, 3)
    .map(({ term, meaning, example }) => ({ term, meaning, example }))
}
