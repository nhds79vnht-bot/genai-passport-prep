function q(chapter, topic, prompt, correct, distractors, explanation, multi = false) {
  const choices = multi ? [...correct, ...distractors] : [correct[0], ...distractors]
  const answers = multi
    ? correct.map((text) => choices.indexOf(text)).sort((a, b) => a - b)
    : [0]
  if (!multi) {
    const idx = choices.indexOf(correct[0])
    if (idx !== 0) {
      const c0 = choices[0]
      choices[0] = choices[idx]
      choices[idx] = c0
    }
  }
  return { chapter, topic, prompt, choices, answers, explanation }
}

